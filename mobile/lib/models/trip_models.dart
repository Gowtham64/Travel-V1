      lunch: ln,
      teaSnacks: ts,
      dinner: dn,
      food: foodTotal > 0 ? foodTotal : calculatedFood,
      other: otherVal,
      stay: (b['stay'] as num?)?.toInt() ?? 0,
      buffer: (b['buffer'] as num?)?.toInt() ?? otherVal,
      total: (json['total'] as num?)?.toInt() ?? 0,
      perDay: (json['perDay'] as num?)?.toInt() ?? 0,
    );
  }

