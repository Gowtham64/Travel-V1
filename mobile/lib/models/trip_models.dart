/// Authoritative Route Information from the backend routing engine.
class RouteInfo {
  final int distanceMeters;
  final double distanceKm;
  final int durationSeconds;
  final int durationMin;
  final List<GeoPoint> coordinates;
  final Map<String, dynamic>? geometry;
  final List<CanonicalRouteLeg> legs;
  final List<CanonicalRouteStep> steps;
  final List<String> maneuvers;
  final bool avoidedMotorways;
  final String provider;

  const RouteInfo({
    required this.distanceMeters,
    required this.distanceKm,
    required this.durationSeconds,
    required this.durationMin,
    required this.coordinates,
    this.geometry,
    this.legs = const [],
    this.steps = const [],
    this.maneuvers = const [],
    this.avoidedMotorways = false,
    this.provider = 'authoritative',
  });

  factory RouteInfo.fromJson(Map<String, dynamic> json) {
    final distM = (json['distanceMeters'] as num?)?.toInt() ??
        (((json['distanceKm'] as num?)?.toDouble() ?? 0.0) * 1000).round();
    final distKm = (json['distanceKm'] as num?)?.toDouble() ?? (distM / 1000.0);
    final durSec = (json['durationSeconds'] as num?)?.toInt() ??
        (((json['durationMin'] as num?)?.toInt() ?? 0) * 60);
    final durMin = (json['durationMin'] as num?)?.toInt() ?? (durSec / 60).round();

    final coords = (json['coordinates'] as List? ?? [])
        .map((e) => GeoPoint.fromJson((e as Map).cast<String, dynamic>()))
        .toList();

    final legs = (json['legs'] as List? ?? [])
        .map((e) => CanonicalRouteLeg.fromJson((e as Map).cast<String, dynamic>()))
        .toList();

    final steps = (json['steps'] as List? ?? [])
        .map((e) => CanonicalRouteStep.fromJson((e as Map).cast<String, dynamic>()))
        .toList();

    final maneuvers = (json['maneuvers'] as List? ?? [])
        .map((e) => e.toString())
        .toList();

    return RouteInfo(
      distanceMeters: distM,
      distanceKm: distKm,
      durationSeconds: durSec,
      durationMin: durMin,
      coordinates: coords,
      geometry: json['geometry'] != null ? (json['geometry'] as Map).cast<String, dynamic>() : null,
      legs: legs,
      steps: steps,
      maneuvers: maneuvers,
      avoidedMotorways: json['avoidedMotorways'] == true,
      provider: json['provider']?.toString() ?? 'authoritative',
    );
  }

  Map<String, dynamic> toJson() => {
    'distanceMeters': distanceMeters,
    'distanceKm': distanceKm,
    'durationSeconds': durationSeconds,
    'durationMin': durationMin,
    'coordinates': coordinates.map((c) => c.toJson()).toList(),
    if (geometry != null) 'geometry': geometry,
    'legs': legs.map((l) => l.toJson()).toList(),
    'steps': steps.map((s) => s.toJson()).toList(),
    'maneuvers': maneuvers,
    'avoidedMotorways': avoidedMotorways,
    'provider': provider,
  };

  String get formattedDistance => TripPlan.formatDistance(distanceKm, distMeters: distanceMeters);
}

/// Authoritative Navigation Route contract containing all stops as waypoints.
class NavigationRoute {
  final GeoPoint origin;
  final GeoPoint destination;
  final List<GeoPoint> waypoints;
  final double distanceKm;
  final int distanceMeters;
  final int durationMin;
  final int durationSeconds;
  final List<GeoPoint> coordinates;
  final Map<String, dynamic>? geometry;

  const NavigationRoute({
    required this.origin,
    required this.destination,
    required this.waypoints,
    required this.distanceKm,
    required this.distanceMeters,
    required this.durationMin,
    required this.durationSeconds,
    required this.coordinates,
    this.geometry,
  });

  factory NavigationRoute.fromJson(Map<String, dynamic> json) {
    final distKm = (json['distanceKm'] as num?)?.toDouble() ?? 0.0;
    final distM = (json['distanceMeters'] as num?)?.toInt() ?? (distKm * 1000).round();
    final durMin = (json['durationMin'] as num?)?.toInt() ?? 0;
    final durSec = (json['durationSeconds'] as num?)?.toInt() ?? (durMin * 60);

    return NavigationRoute(
      origin: GeoPoint.fromJson((json['origin'] as Map).cast<String, dynamic>()),
      destination: GeoPoint.fromJson((json['destination'] as Map).cast<String, dynamic>()),
      waypoints: (json['waypoints'] as List? ?? [])
          .map((e) => GeoPoint.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      distanceKm: distKm,
      distanceMeters: distM,
      durationMin: durMin,
      durationSeconds: durSec,
      coordinates: (json['coordinates'] as List? ?? [])
          .map((e) => GeoPoint.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      geometry: json['geometry'] != null ? (json['geometry'] as Map).cast<String, dynamic>() : null,
    );
  }

  Map<String, dynamic> toJson() => {
    'origin': origin.toJson(),
    'destination': destination.toJson(),
    'waypoints': waypoints.map((w) => w.toJson()).toList(),
    'distanceKm': distanceKm,
    'distanceMeters': distanceMeters,
    'durationMin': durationMin,
    'durationSeconds': durationSeconds,
    'coordinates': coordinates.map((c) => c.toJson()).toList(),
    if (geometry != null) 'geometry': geometry,
  };
}

class TripPlan {
  final double distanceKm;
  final int distanceMeters;
  final int durationMin;
  final int durationSeconds;
  final List<GeoPoint> coordinates;

  /// True when expressways/motorways were excluded from this route because the
  /// vehicle (2-/3-wheeler) is legally barred from them.
  final bool avoidedMotorways;
  final int estimatedDays;
  final FuelPlan fuel;
  final FuelEstimate? fuelEstimate;
  final TollEstimate? toll;
  final RouteWeather? weather;
  final DepartureAdvice? departureAdvice;
  final List<RestBreak> restStops;
  final List<DayPlan> itinerary;
  final TripBudget? budget;
  final Map<String, List<PlaceOfInterest>> places;
  final List<WikiAttraction> wikiAttractions;
  final List<DestinationEvent> events;
  final List<GeoPoint> navigationWaypoints;
  final List<CanonicalRouteLeg> legs;
  final List<CanonicalRouteStep> steps;
  final List<String> maneuvers;
  final Map<String, dynamic>? geometry;
  final String? provider;
  final Vehicle? vehicleSnapshot;

  TripPlan({
    required this.distanceKm,
    int? distanceMeters,
    required this.durationMin,
    int? durationSeconds,
    required this.coordinates,
    this.avoidedMotorways = false,
    required this.estimatedDays,
    required this.fuel,
    this.fuelEstimate,
    required this.toll,
    required this.weather,
    required this.departureAdvice,
    required this.restStops,
    required this.itinerary,
    required this.budget,
    required this.places,
    this.wikiAttractions = const [],
    this.events = const [],
    this.navigationWaypoints = const [],
    this.legs = const [],
    this.steps = const [],
    this.maneuvers = const [],
    this.geometry,
    this.provider,
    this.vehicleSnapshot,
  })  : distanceMeters = distanceMeters ?? ((distanceKm * 1000).round()),
        durationSeconds = durationSeconds ?? (durationMin * 60);

  /// Centralized distance formatter across all platforms
  static String formatDistance(double distKm, {int? distMeters}) {
    final m = distMeters ?? (distKm * 1000).round();
    if (m < 1000) {
      return '$m m';
    } else {
      return '${(m / 1000.0).toStringAsFixed(1)} km';
    }
  }

  String get formattedDistance => formatDistance(distanceKm, distMeters: distanceMeters);

  factory TripPlan.fromJson(Map<String, dynamic> json) {
    final route = (json['route'] as Map).cast<String, dynamic>();
    final placesJson = ((json['places'] as Map?) ?? {}).cast<String, dynamic>();

    final distKm = (route['distanceKm'] as num).toDouble();
    final distMeters = (route['distanceMeters'] as num?)?.toInt() ?? (distKm * 1000).round();
    final durMin = (route['durationMin'] as num?)?.toInt() ?? 0;
    final durSec = (route['durationSeconds'] as num?)?.toInt() ?? (durMin * 60);

    return TripPlan(
      distanceKm: distKm,
      distanceMeters: distMeters,
      durationMin: durMin,
      durationSeconds: durSec,
      coordinates: (route['coordinates'] as List)
          .map((e) => GeoPoint.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      avoidedMotorways: (route['avoidedMotorways'] as bool?) ?? false,
      estimatedDays: json['estimatedDays'] as int,
      fuel: FuelPlan.fromJson((json['fuel'] as Map).cast<String, dynamic>()),
      fuelEstimate: json['fuelEstimate'] != null
          ? FuelEstimate.fromJson((json['fuelEstimate'] as Map).cast<String, dynamic>())
          : null,
      toll: json['toll'] != null ? TollEstimate.fromJson((json['toll'] as Map).cast<String, dynamic>()) : null,
      weather: json['weather'] != null ? RouteWeather.fromJson((json['weather'] as Map).cast<String, dynamic>()) : null,
      departureAdvice: json['departureAdvice'] != null
          ? DepartureAdvice.fromJson((json['departureAdvice'] as Map).cast<String, dynamic>())
          : null,
      restStops: (json['restStops'] as List? ?? [])
          .map((e) => RestBreak.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      itinerary: (json['itinerary'] as List? ?? [])
          .map((e) => DayPlan.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      budget: json['budget'] != null ? TripBudget.fromJson((json['budget'] as Map).cast<String, dynamic>()) : null,
      places: placesJson.map(
        (key, value) => MapEntry(
          key,
          (value as List).map((e) => PlaceOfInterest.fromJson((e as Map).cast<String, dynamic>())).toList(),
        ),
      ),
      wikiAttractions: (json['wikiAttractions'] as List? ?? [])
          .map((e) => WikiAttraction.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      events: (json['events'] as List? ?? [])
          .map((e) => DestinationEvent.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      navigationWaypoints: ((json['navigationWaypoints'] as List?) ?? [])
          .map((e) => GeoPoint.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      legs: ((route['legs'] as List?) ?? [])
          .map((e) => CanonicalRouteLeg.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      steps: ((route['steps'] as List?) ?? [])
          .map((e) => CanonicalRouteStep.fromJson((e as Map).cast<String, dynamic>()))
          .toList(),
      maneuvers: ((route['maneuvers'] as List?) ?? [])
          .map((e) => e.toString())
          .toList(),
      geometry: (route['geometry'] as Map?)?.cast<String, dynamic>(),
      provider: route['provider'] as String?,
      vehicleSnapshot: json['vehicleSnapshot'] != null
          ? Vehicle.fromJson((json['vehicleSnapshot'] as Map).cast<String, dynamic>())
          : null,
    );
  }

  TripPlan copyWith({
    double? distanceKm,
    int? distanceMeters,
    int? durationMin,
