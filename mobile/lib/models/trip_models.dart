import 'package:latlong2/latlong.dart';

class GeoPoint {
  final double lat;
  final double lng;
  final String? name;
  final bool isFuelStop;
  final RefuelStop? refuelStop;

  const GeoPoint({
    required this.lat,
    required this.lng,
    this.name,
    this.isFuelStop = false,
    this.refuelStop,
  });

  factory GeoPoint.fromJson(Map<String, dynamic> json) =>
      GeoPoint(
        lat: (json['lat'] as num).toDouble(),
        lng: (json['lng'] as num).toDouble(),
        name: json['name'] as String?,
        isFuelStop: (json['isFuelStop'] as bool?) ?? false,
        refuelStop: json['refuelStop'] != null
            ? RefuelStop.fromJson(json['refuelStop'] as Map<String, dynamic>)
            : null,
      );

  LatLng toLatLng() => LatLng(lat, lng);

  Map<String, dynamic> toJson() => {
        'lat': lat,
        'lng': lng,
        if (name != null) 'name': name,
        'isFuelStop': isFuelStop,
      };
}

class Vehicle {
  final String type; // car | suv | motorcycle | bus | rv | truck2axle | truck3axle
  final double efficiencyKmPerLiter;
  final double tankCapacityLiters;
  final double currentFuelLiters;
  final String fuelType; // petrol | diesel | cng | ev
  final bool isCustomEfficiency;

  const Vehicle({
    required this.type,
    required this.efficiencyKmPerLiter,
    required this.tankCapacityLiters,
    required this.currentFuelLiters,
    this.fuelType = 'petrol',
    this.isCustomEfficiency = false,
  });

  Map<String, dynamic> toJson() => {
        'type': type,
        'efficiencyKmPerLiter': efficiencyKmPerLiter,
        'tankCapacityLiters': tankCapacityLiters,
        'currentFuelLiters': currentFuelLiters,
        'fuelType': fuelType,
        'isCustomEfficiency': isCustomEfficiency,
      };

  factory Vehicle.fromJson(Map<String, dynamic> json) => Vehicle(
        type: json['type'] as String? ?? 'car',
        efficiencyKmPerLiter:
            (json['efficiencyKmPerLiter'] as num?)?.toDouble() ?? 15.0,
        tankCapacityLiters:
            (json['tankCapacityLiters'] as num?)?.toDouble() ?? 45.0,
        currentFuelLiters:
            (json['currentFuelLiters'] as num?)?.toDouble() ?? 45.0,
        fuelType: json['fuelType'] as String? ?? 'petrol',
        isCustomEfficiency: json['isCustomEfficiency'] as bool? ?? false,
      );

  Vehicle copyWith({
    String? type,
    double? efficiencyKmPerLiter,
    double? tankCapacityLiters,
    double? currentFuelLiters,
    String? fuelType,
    bool? isCustomEfficiency,
  }) {
    return Vehicle(
      type: type ?? this.type,
      efficiencyKmPerLiter: efficiencyKmPerLiter ?? this.efficiencyKmPerLiter,
      tankCapacityLiters: tankCapacityLiters ?? this.tankCapacityLiters,
      currentFuelLiters: currentFuelLiters ?? this.currentFuelLiters,
      fuelType: fuelType ?? this.fuelType,
      isCustomEfficiency: isCustomEfficiency ?? this.isCustomEfficiency,
    );
  }
}

class RefuelStop {
  final double lat;
  final double lng;
  final double distanceFromStartKm;

  /// Name of the real fuel station this stop snaps to.
  final String name;

  /// Station id when snapped to a real pump.
  final dynamic stationId;

  /// How far this station sits off the driving route, in km.
  final double? offRouteKm;

  /// Estimated fuel left in the tank when arriving at this station, in litres.
  final double? fuelOnArrivalLiters;

  /// Refill amount needed to top up to full capacity (litres).
  final double? refillLiters;

  /// Estimated cost for this top up refill.
  final double? estimatedCost;

  /// Unit price per litre/kWh at this location.
  final double? pricePerUnit;

  /// Currency code (e.g. INR)
  final String currency;

  /// Currency symbol (e.g. ₹)
  final String currencySymbol;

  /// Fuel type (petrol, diesel, cng, ev)
  final String fuelType;

  /// Full driving range available after refuelling (km).
  final double? remainingRangeAfterRefuelKm;

  /// Whether this stop was automatically generated by VoyPlan's smart fuel engine.
  final bool isSystemGenerated;

  /// Trip leg index where this refuel occurs (0 = first leg before Stop 1, etc.)
  final int legIndex;

  const RefuelStop({
    required this.lat,
    required this.lng,
    required this.distanceFromStartKm,
    this.name = '',
    this.stationId,
    this.offRouteKm,
    this.fuelOnArrivalLiters,
    this.refillLiters,
    this.estimatedCost,
    this.pricePerUnit,
    this.currency = 'INR',
    this.currencySymbol = '₹',
    this.fuelType = 'petrol',
    this.remainingRangeAfterRefuelKm,
    this.isSystemGenerated = true,
    this.legIndex = 0,
  });

  /// True when this stop is a real, named fuel station rather than a geometric marker.
  bool get isRealStation => name.isNotEmpty;

  factory RefuelStop.fromJson(Map<String, dynamic> json) => RefuelStop(
        lat: ((json['lat'] ?? json['latitude']) as num?)?.toDouble() ?? 0.0,
        lng: ((json['lng'] ?? json['longitude']) as num?)?.toDouble() ?? 0.0,
        distanceFromStartKm: (json['distanceFromStartKm'] as num?)?.toDouble() ?? 0.0,
        name: (json['name'] as String?) ?? '',
        stationId: json['stationId'] ?? json['id'],
        offRouteKm: ((json['offRouteKm'] ?? json['distanceFromRoute']) as num?)?.toDouble(),
        fuelOnArrivalLiters: (json['fuelOnArrivalLiters'] as num?)?.toDouble(),
        refillLiters: (json['refillLiters'] as num?)?.toDouble(),
        estimatedCost: (json['estimatedCost'] as num?)?.toDouble(),
        pricePerUnit: (json['pricePerUnit'] as num?)?.toDouble(),
        currency: (json['currency'] as String?) ?? 'INR',
        currencySymbol: (json['currencySymbol'] as String?) ?? '₹',
        fuelType: (json['fuelType'] as String?) ?? 'petrol',
        remainingRangeAfterRefuelKm: (json['remainingRangeAfterRefuelKm'] as num?)?.toDouble(),
        isSystemGenerated: (json['isSystemGenerated'] as bool?) ?? true,
        legIndex: (json['legIndex'] as num?)?.toInt() ?? 0,
      );

  String get id => stationId?.toString() ?? 'fuel_${lat.toStringAsFixed(4)}_${lng.toStringAsFixed(4)}';
  String get type => 'fuel_stop';
  double get latitude => lat;
  double get longitude => lng;
  double get distanceFromRoute => offRouteKm ?? 0.0;
  double get estimatedFuelRequired => refillLiters ?? 0.0;

  GeoPoint toGeoPoint() => GeoPoint(
        lat: lat,
        lng: lng,
        name: name.isNotEmpty ? name : 'Fuel Station',
        isFuelStop: true,
        refuelStop: this,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'type': type,
        'name': name,
        'lat': lat,
        'lng': lng,
        'latitude': latitude,
        'longitude': longitude,
        'stationId': stationId,
        'distanceFromStartKm': distanceFromStartKm,
        'distanceFromRoute': distanceFromRoute,
        'offRouteKm': offRouteKm,
        'fuelOnArrivalLiters': fuelOnArrivalLiters,
        'refillLiters': refillLiters,
        'estimatedFuelRequired': estimatedFuelRequired,
        'estimatedCost': estimatedCost,
        'pricePerUnit': pricePerUnit,
        'currency': currency,
        'currencySymbol': currencySymbol,
        'fuelType': fuelType,
        'remainingRangeAfterRefuelKm': remainingRangeAfterRefuelKm,
        'isSystemGenerated': isSystemGenerated,
        'legIndex': legIndex,
      };

  LatLng toLatLng() => LatLng(lat, lng);
}

/// A hiking/trekking trail surfaced by the AllTrails-style discovery feature.
class Trek {
  final String id;
  final String name;
  final double lat;
  final double lng;
  final double distanceFromSearchKm;
  final double? lengthKm;
  final String? difficulty;
  final String type;
  final String? description;
  final String? imageUrl;

  /// Ordered trail geometry (may be empty when OSM has no line for it).
  final List<LatLng> path;

  const Trek({
    required this.id,
    required this.name,
    required this.lat,
    required this.lng,
    required this.distanceFromSearchKm,
    this.lengthKm,
    this.difficulty,
    this.type = 'trail',
    this.description,
    this.imageUrl,
    this.path = const [],
  });

  bool get hasPath => path.length > 1;

  LatLng toLatLng() => LatLng(lat, lng);
  GeoPoint toGeoPoint() => GeoPoint(lat: lat, lng: lng, name: name);

  factory Trek.fromJson(Map<String, dynamic> json) => Trek(
        id: json['id'] as String,
        name: json['name'] as String,
        lat: (json['lat'] as num).toDouble(),
        lng: (json['lng'] as num).toDouble(),
        distanceFromSearchKm: (json['distanceFromSearchKm'] as num?)?.toDouble() ?? 0,
        lengthKm: (json['lengthKm'] as num?)?.toDouble(),
        difficulty: json['difficulty'] as String?,
        type: (json['type'] as String?) ?? 'trail',
        description: json['description'] as String?,
        imageUrl: json['imageUrl'] as String?,
        path: (json['path'] as List? ?? [])
            .map((e) => LatLng(
                  ((e as Map)['lat'] as num).toDouble(),
                  (e['lng'] as num).toDouble(),
                ))
            .toList(),
      );
}

/// One time block in the smart AI itinerary timeline.
class TimelineBlock {
  final String id;
  String start;
  String end;
  final String type; // start|activity|travel|meal|coffee|rest|checkin|checkout|buffer|shopping|freetime|return|fuel
  String title;
  final String place;
  final double? lat;
  final double? lng;
  final String address;
  final String city;
  final String state;
  final String country;
  int durationMin;
  final int travelMin;
  final double distanceKm;
  final String breakType; // breakfast|lunch|dinner|tea (for meal/break blocks)
  final String reason;
  final String travelMode; // drive|flight|train|bus|ferry|walk (travel/return legs)
  final List<String> categories; // matched place categories
  final String whyIncluded; // explanation for why this stop was chosen
  final String openingHours;
  final int day;
  final int sequence;
  final bool isFuelStop;
  bool isConfirmed;
  final String placeId;
  int stayDuration;

  TimelineBlock({
    this.id = '',
    required this.start,
    required this.end,
    required this.type,
    required this.title,
    this.place = '',
    this.lat,
    this.lng,
    this.address = '',
    this.city = '',
    this.state = '',
    this.country = 'India',
    this.durationMin = 0,
    this.travelMin = 0,
    this.distanceKm = 0,
    this.breakType = '',
    this.reason = '',
    this.travelMode = '',
    this.categories = const [],
    this.whyIncluded = '',
    this.openingHours = '',
    this.day = 1,
    this.sequence = 0,
    this.isFuelStop = false,
    this.isConfirmed = false,
    this.placeId = '',
    int? stayDuration,
  }) : stayDuration = stayDuration ?? durationMin;

  factory TimelineBlock.fromJson(Map<String, dynamic> j) {
    final dMin = (j['durationMin'] as num?)?.toInt() ?? 0;
    return TimelineBlock(
        id: (j['id'] ?? '').toString(),
        start: (j['start'] ?? '').toString(),
        end: (j['end'] ?? '').toString(),
        type: (j['type'] ?? 'activity').toString(),
        title: (j['title'] ?? '').toString(),
        place: (j['place'] ?? '').toString(),
        lat: (j['lat'] as num?)?.toDouble() ?? (j['latitude'] as num?)?.toDouble(),
        lng: (j['lng'] as num?)?.toDouble() ?? (j['longitude'] as num?)?.toDouble(),
        address: (j['address'] ?? '').toString(),
        city: (j['city'] ?? '').toString(),
        state: (j['state'] ?? '').toString(),
        country: (j['country'] ?? 'India').toString(),
        durationMin: dMin,
        travelMin: (j['travelMin'] as num?)?.toInt() ?? 0,
        distanceKm: (j['distanceKm'] as num?)?.toDouble() ?? 0,
        breakType: (j['breakType'] ?? '').toString(),
        reason: (j['reason'] ?? '').toString(),
        travelMode: (j['travelMode'] ?? '').toString(),
        categories: (j['categories'] as List? ?? [])
            .map((e) => e.toString())
            .where((s) => s.isNotEmpty)
            .toList(),
        whyIncluded: (j['whyIncluded'] ?? '').toString(),
        openingHours: (j['openingHours'] ?? '').toString(),
        day: (j['day'] as num?)?.toInt() ?? 1,
        sequence: (j['sequence'] as num?)?.toInt() ?? 0,
        isFuelStop: j['isFuelStop'] == true || j['type'] == 'fuel',
        isConfirmed: j['isConfirmed'] == true,
        placeId: (j['placeId'] ?? '').toString(),
        stayDuration: (j['stayDuration'] as num?)?.toInt() ?? dMin,
      );
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'start': start,
        'end': end,
        'type': type,
        'title': title,
        'place': place,
        'lat': lat,
        'lng': lng,
        'address': address,
        'city': city,
        'state': state,
        'country': country,
        'durationMin': durationMin,
        'travelMin': travelMin,
        'distanceKm': distanceKm,
        'breakType': breakType,
        'reason': reason,
        'travelMode': travelMode,
        'categories': categories,
        'whyIncluded': whyIncluded,
        'openingHours': openingHours,
        'day': day,
        'sequence': sequence,
        'isFuelStop': isFuelStop,
        'isConfirmed': isConfirmed,
        'placeId': placeId,
        'stayDuration': stayDuration,
      };
}

