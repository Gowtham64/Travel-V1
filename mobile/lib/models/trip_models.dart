        'day': day,
        'date': date,
        'title': title,
        'blocks': blocks.map((b) => b.toJson()).toList(),
      };
}


class FuelPlan {
  final bool needsRefuel;
  final double totalDistanceKm;
  final List<RefuelStop> refuelStops;

  /// True when part of the route has no reachable fuel station within
  /// the vehicle's safe driving range — signals a critical warning.
  final bool unreachable;

  /// Safe planning range with reserve (km).
  final double? safeRangeKm;

  /// Human-readable explanation if unreachable.
  final String? unreachableReason;

  /// Total estimated cost for all planned refuels along the trip.
  final double? totalRefuelCost;

  /// Total liters/units to be refilled across all stops.
  final double? totalRefillLiters;

  const FuelPlan({
    required this.needsRefuel,
    required this.totalDistanceKm,
    required this.refuelStops,
    this.unreachable = false,
    this.safeRangeKm,
    this.unreachableReason,
    this.totalRefuelCost,
    this.totalRefillLiters,
  });

  factory FuelPlan.fromJson(Map<String, dynamic> json) => FuelPlan(
        needsRefuel: json['needsRefuel'] as bool? ?? false,
        totalDistanceKm: (json['totalDistanceKm'] as num?)?.toDouble() ?? 0.0,
        unreachable: (json['unreachable'] as bool?) ?? false,
        safeRangeKm: (json['safeRangeKm'] as num?)?.toDouble(),
        unreachableReason: json['unreachableReason'] as String?,
        totalRefuelCost: (json['totalRefuelCost'] as num?)?.toDouble(),
        totalRefillLiters: (json['totalRefillLiters'] as num?)?.toDouble(),
        refuelStops: ((json['refuelStops'] as List?) ?? [])
            .map((e) => RefuelStop.fromJson(e as Map<String, dynamic>))
            .toList(),
      );
}

class FuelPrice {
  final String country;
  final String countryCode;
  final String state;
  final String city;
  final String fuelType;
  final double price;
  final String currency;
  final String currencySymbol;
  final String unit;
  final String effectiveAt;
  final String lastUpdated;
  final String source;
  final String status; // 'live' | 'cached' | 'estimated' | 'unavailable'
  final String confidence; // 'high' | 'medium' | 'low'
  final Map<String, double> allPrices;

  const FuelPrice({
    required this.country,
    this.countryCode = 'IN',
    required this.state,
    required this.city,
    required this.fuelType,
    required this.price,
    this.currency = 'INR',
    this.currencySymbol = '₹',
    this.unit = 'litre',
    required this.effectiveAt,
    required this.lastUpdated,
    this.source = 'PPAC / Official OMC Daily RSP',
    this.status = 'live',
    this.confidence = 'high',
    this.allPrices = const {},
  });

  factory FuelPrice.fromJson(Map<String, dynamic> json) {
    final pricesMap = <String, double>{};
    if (json['allPrices'] is Map) {
      (json['allPrices'] as Map).forEach((k, v) {
        if (v is num) pricesMap[k.toString()] = v.toDouble();
      });
    }

    return FuelPrice(
      country: json['country'] as String? ?? 'India',
      countryCode: json['countryCode'] as String? ?? 'IN',
      state: json['state'] as String? ?? 'Karnataka',
      city: json['city'] as String? ?? 'Bengaluru',
      fuelType: json['fuelType'] as String? ?? 'petrol',
      price: (json['price'] as num?)?.toDouble() ?? 102.86,
      currency: json['currency'] as String? ?? 'INR',
      currencySymbol: json['currencySymbol'] as String? ?? '₹',
      unit: json['unit'] as String? ?? 'litre',
      effectiveAt: json['effectiveAt'] as String? ?? DateTime.now().toIso8601String(),
      lastUpdated: json['lastUpdated'] as String? ?? DateTime.now().toIso8601String(),
      source: json['source'] as String? ?? 'Official OMC Daily RSP',
      status: json['status'] as String? ?? 'live',
      confidence: json['confidence'] as String? ?? 'high',
      allPrices: pricesMap,
    );
  }

  Map<String, dynamic> toJson() => {
        'country': country,
        'countryCode': countryCode,
        'state': state,
        'city': city,
        'fuelType': fuelType,
        'price': price,
        'currency': currency,
        'currencySymbol': currencySymbol,
        'unit': unit,
        'effectiveAt': effectiveAt,
        'lastUpdated': lastUpdated,
        'source': source,
        'status': status,
        'confidence': confidence,
        'allPrices': allPrices,
      };

  bool get isRealTime => status == 'live';
  String get provider => source;
}

class FuelEstimate {
  final double distanceKm;
  final double vehicleEfficiency;
  final String fuelType;
  final double fuelRequired;
  final double pricePerUnit;
  final String currency;
  final String currencySymbol;
  final String unit;
  final double totalCost;
  final String startRegion;
  final String endRegion;
  final bool isMultiState;
  final bool isDefaultMileage;
  final String source;
  final String effectiveAt;
  final String lastUpdated;
  final double currentFuelLiters;
  final double additionalFuelRequiredLiters;
  final double estimatedCost;
  final String applicableLocation;
  final String updatedAtText;
  final String status;

  const FuelEstimate({
    required this.distanceKm,
    required this.vehicleEfficiency,
    required this.fuelType,
    required this.fuelRequired,
    required this.pricePerUnit,
    this.currentFuelLiters = 0.0,
    this.additionalFuelRequiredLiters = 0.0,
    this.estimatedCost = 0.0,
    this.currency = 'INR',
    this.currencySymbol = '₹',
    this.unit = 'litre',
    required this.totalCost,
    this.startRegion = '',
    this.endRegion = '',
    this.applicableLocation = '',
    this.isMultiState = false,
    this.isDefaultMileage = false,
    this.source = 'CarDekho / OMC Daily Retail Price',
    this.updatedAtText = 'Updated: Today',
    required this.effectiveAt,
    required this.lastUpdated,
    this.status = 'live',
  });

  double get totalFuelCost => totalCost;
  double get fuelRequiredLiters => fuelRequired;
  double get appliedPricePerLiter => pricePerUnit;
  double get estimatedFuelCost => estimatedCost > 0 ? estimatedCost : totalCost;
  bool get isPriceAvailable => status.toLowerCase() != 'unavailable' && pricePerUnit > 0;

  String get formattedFuelRequired => '${fuelRequired.toStringAsFixed(1)} L';
  String get formattedCurrentFuel => '${currentFuelLiters.toStringAsFixed(1)} L';
  String get formattedAdditionalRequired => '${additionalFuelRequiredLiters.toStringAsFixed(1)} L';
  String get formattedFuelPrice => isPriceAvailable
      ? '$currencySymbol${pricePerUnit.toStringAsFixed(2)}/${unit == "litre" ? "L" : unit}'
      : 'Fuel price unavailable';
  String get formattedEstimatedCost => '$currencySymbol${(estimatedCost > 0 ? estimatedCost : totalCost).toStringAsFixed(2)}';

  String get regionName => applicableLocation.isNotEmpty
      ? applicableLocation
      : (startRegion.isNotEmpty
          ? (endRegion.isNotEmpty && isMultiState ? '$startRegion ➔ $endRegion' : startRegion)
          : 'India');
  String get priceWithLocation => '$formattedFuelPrice ($regionName)';
  bool get isMultiRegionEstimate => isMultiState;
  String get dataSource => source;

  factory FuelEstimate.fromJson(Map<String, dynamic> json) {
    final req = (json['fuelRequired'] as num?)?.toDouble() ??
        (json['fuelRequiredLiters'] as num?)?.toDouble() ?? 0.0;
    final cur = (json['currentFuelLiters'] as num?)?.toDouble() ?? 0.0;
    final add = (json['additionalFuelRequiredLiters'] as num?)?.toDouble() ??
        ((req - cur) > 0 ? req - cur : 0.0);
    final tot = (json['totalCost'] as num?)?.toDouble() ??
        (json['totalFuelCost'] as num?)?.toDouble() ?? 0.0;
    final est = (json['estimatedCost'] as num?)?.toDouble() ?? tot;

    return FuelEstimate(
      distanceKm: (json['distanceKm'] as num?)?.toDouble() ?? 0.0,
      vehicleEfficiency: (json['vehicleEfficiency'] as num?)?.toDouble() ?? 15.0,
      fuelType: json['fuelType'] as String? ?? 'petrol',
      fuelRequired: req,
      currentFuelLiters: cur,
