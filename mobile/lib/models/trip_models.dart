  final int fuel;
  final int tolls;
  final int transport; // flight/train/bus/ferry tickets
  final int localTransport; // destination taxis / local getting-around
  final int breakfast;
  final int lunch;
  final int teaSnacks;
  final int dinner;
  final int food;
  final int other;
  final int stay;
  final int buffer;
  final int total;
  final int perDay;

  const TripBudget({
    required this.currency,
    required this.days,
    required this.nights,
    required this.travellers,
    this.international = false,
    required this.fuel,
    required this.tolls,
    this.transport = 0,
    this.localTransport = 0,
    this.breakfast = 0,
    this.lunch = 0,
    this.teaSnacks = 0,
    this.dinner = 0,
    required this.food,
