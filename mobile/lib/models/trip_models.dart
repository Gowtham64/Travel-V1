      navigationWaypoints: navigationWaypoints ?? this.navigationWaypoints,
      legs: legs ?? this.legs,
      steps: steps ?? this.steps,
      maneuvers: maneuvers ?? this.maneuvers,
      geometry: geometry ?? this.geometry,
      provider: provider ?? this.provider,
